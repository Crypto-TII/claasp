#!/usr/bin/env python3
"""Generate a single KATAN32 results table from AND-operation logs."""

import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from generate_lea_latex_tables import (
    bold_latex_cell,
    extract_test_params_from_dirname,
    format_probability_exponent,
    round_to_two_decimals,
    test_directory_sort_key,
)
from generate_single_key_chacha_latex_tables import DONE, SOLUTION


Parameters = Tuple[int, int, int, int]
Weights = Tuple[float, float, float, float]


@dataclass(frozen=True)
class Result:
    params: Parameters
    weights: Optional[Weights]
    time: Optional[float]


def parse_log(path: Path, params: Parameters) -> Result:
    content = path.read_text(encoding="utf-8")
    solutions = list(SOLUTION.finditer(content))
    done = list(DONE.finditer(content))
    weights = (
        tuple(float(solutions[-1].group(i)) for i in (1, 2, 3, 4))
        if solutions else None
    )
    time = float(done[-1].group(1)) if done else None
    if weights is None and time is not None and not (
        re.search(r"^%%%mzn-stat:\s*nSolutions=0\s*$", content, re.MULTILINE)
        or "=====UNSATISFIABLE=====" in content
        or "=====UNKNOWN=====" in content
    ):
        raise ValueError(f"No solution or no-solution marker in completed log: {path}")
    if weights is None and time is None and re.search(
        r"^(?:Upper|Lower|Middle|Trail) weight\s*=", content, re.MULTILINE
    ):
        print(f"Warning: incomplete solution block in {path}", file=sys.stderr)
    if weights is not None:
        weights = (weights[0], weights[1], weights[2], weights[3])
    return Result(params, weights, time)


def collect_results(base: Path, cipher: str = "katan32") -> Dict[str, List[Result]]:
    if not base.is_dir():
        raise FileNotFoundError(f"{cipher.upper()} test directory not found: {base}")
    aliases = [cipher]
    if cipher.startswith("katan"):
        aliases.append("katan")
    elif cipher.startswith("simon"):
        aliases.append("simon")
    prefixes = "|".join(re.escape(alias) for alias in aliases)
    log_name = re.compile(rf"test_(?:{prefixes})_(\d+r_\d+_\d+_\d+)(?:_seed_\d+)?\.log")
    data: Dict[str, List[Result]] = {}
    for directory in sorted(base.iterdir()):
        if directory.is_dir() and directory.name.startswith("test_"):
            extract_test_params_from_dirname(directory.name)
            data[directory.name] = []

    for path in sorted(base.glob("*.log")) + sorted(base.glob("test_*/*.log")):
        match = log_name.fullmatch(path.name)
        if not match:
            print(f"Warning: unrecognized log filename: {path}", file=sys.stderr)
            continue
        name = f"test_{match.group(1)}"
        if path.parent != base and path.parent.name != name:
            raise ValueError(f"Log filename does not match directory: {path}")
        data.setdefault(name, []).append(parse_log(path, extract_test_params_from_dirname(name)))
    if not data:
        raise ValueError(f"No {cipher.upper()} test configurations found in {base}")
    for name, results in data.items():
        if not results:
            print(f"Warning: no log files for {name}", file=sys.stderr)
    return data


def best_result(results: List[Result]) -> Optional[Result]:
    candidates = [result for result in results if result.weights is not None]
    return min(
        candidates,
        key=lambda result: (
            result.weights[3] if result.weights is not None else float("inf"),
            result.time if result.time is not None else float("inf"),
        ),
        default=None,
    )


def render_table(data: Dict[str, List[Result]], cipher: str = "katan32") -> str:
    selected = {}
    for name, results in data.items():
        selected[name] = best_result(results)
        if selected[name] is None and results:
            selected[name] = min(
                results, key=lambda result: result.time if result.time is not None else float("inf")
            )

    best_by_round: Dict[int, Result] = {}
    for name in sorted(data, key=test_directory_sort_key):
        result = selected[name]
        if result is None or result.weights is None:
            continue
        round_num = result.params[0]
        current = best_by_round.get(round_num)
        if current is None or best_result([current, result]) is result:
            best_by_round[round_num] = result

    lines = [
        f"% {cipher.upper()} Test LaTeX Table",
        f"% Auto-generated by generate_{cipher}_latex_tables.py",
        "% in course: no completion time in the log; -: no available solution or log",
        r"\begin{table}[htbp]",
        r"\centering",
        f"\\caption{{{cipher.upper()} Test Results - Best Probability}}",
        f"\\label{{tab:{cipher}-best-probability}}",
        r"\small",
        r"\begin{tabular}{|c|c|c|c|c|c|c|c|c|}",
        r"\hline",
        r"R & $r_0$ & $r_m$ & $r_1$ & $p$ & $q$ & $r$ & $P_{boom}$ & Time (s) \\",
        r"\hline",
    ]
    for name in sorted(data, key=test_directory_sort_key):
        params = extract_test_params_from_dirname(name)
        result = selected[name]
        cells = [str(value) for value in params]
        cells.extend(
            [format_probability_exponent(weight) for weight in result.weights]
            if result is not None and result.weights is not None else ["-"] * 4
        )
        cells.append(
            "-" if result is None else
            "in course" if result.time is None else round_to_two_decimals(result.time)
        )
        if result is not None and best_by_round.get(params[0]) is result:
            cells = [bold_latex_cell(cell) for cell in cells]
        lines.append(" & ".join(cells) + r" \\")
    lines.extend([r"\hline", r"\end{tabular}", r"\end{table}", ""])
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parent
    data = collect_results(root / "test_operation_and" / "test_katan32")
    output = root / "katan32_tables.tex"
    output.write_text(render_table(data), encoding="utf-8")
    print(f"Generated 1 table from {sum(map(len, data.values()))} logs "
          f"and {len(data)} configurations: {output}")


if __name__ == "__main__":
    main()
