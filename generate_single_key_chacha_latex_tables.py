#!/usr/bin/env python3
"""Generate tables for ChaCha logs, including unfinished and unsolved runs."""

import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from generate_lea_latex_tables import (
    bold_latex_cell,
    extract_seed_from_filename,
    extract_test_params_from_dirname,
    format_probability_exponent,
    round_to_two_decimals,
    test_directory_sort_key,
)


NUMBER = r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?"
SOLUTION = re.compile(
    rf"^Upper weight\s*=\s*({NUMBER})\s*\n"
    rf"Lower weight\s*=\s*({NUMBER})\s*\n"
    rf"Middle weight\s*=\s*({NUMBER})\s*\n"
    rf"Trail weight\s*=\s*({NUMBER})\s*$",
    re.MULTILINE,
)
DONE = re.compile(rf"Done \(overall time\s+({NUMBER})\s+s\)")


@dataclass(frozen=True)
class Run:
    seed: int
    weights: Optional[Tuple[float, float, float, float]]
    time: Optional[float]


def parse_run(path: Path) -> Run:
    content = path.read_text(encoding="utf-8")
    solutions = list(SOLUTION.finditer(content))
    done = list(DONE.finditer(content))
    time = float(done[-1].group(1)) if done else None
    weights = (
        (float(solutions[-1].group(1)), float(solutions[-1].group(2)),
         float(solutions[-1].group(3)), float(solutions[-1].group(4)))
        if solutions else None
    )
    if weights is None and time is not None:
        if not re.search(r"^%%%mzn-stat:\s*nSolutions=0\s*$", content, re.MULTILINE):
            raise ValueError(f"No solution or no-solution marker in completed log: {path}")
    if weights is None and time is None and re.search(
        r"^(?:Upper|Lower|Middle|Trail) weight\s*=", content, re.MULTILINE
    ):
        print(f"Warning: incomplete solution block in {path}", file=sys.stderr)
    return Run(extract_seed_from_filename(path.name), weights, time)


def collect_runs(base: Path, log_cipher: str = "chacha") -> Dict[str, List[Run]]:
    if not base.is_dir():
        raise FileNotFoundError(f"Test directory not found: {base}")
    result = {}
    for directory in sorted(base.iterdir()):
        if not directory.is_dir() or not directory.name.startswith("test_"):
            continue
        extract_test_params_from_dirname(directory.name)
        logs = sorted(directory.glob(f"test_{log_cipher}_*_seed_*.log"))
        if not logs:
            print(f"Warning: no {log_cipher} seed logs in {directory}", file=sys.stderr)
        result[directory.name] = [parse_run(path) for path in logs]
    if not result:
        raise ValueError(f"No test directories found in {base}")
    return result


def best_run(runs: List[Run]) -> Optional[Run]:
    candidates = [run for run in runs if run.weights is not None]
    return min(
        candidates,
        key=lambda run: (
            run.weights[3] if run.weights is not None else float("inf"),
            run.time if run.time is not None else float("inf"),
            run.seed,
        ),
        default=None,
    )


def result_cells(run: Optional[Run]) -> List[str]:
    if run is None:
        return ["-"] * 6
    probabilities = (
        [format_probability_exponent(weight) for weight in run.weights]
        if run.weights is not None else ["-"] * 4
    )
    time = round_to_two_decimals(run.time) if run.time is not None else "in course"
    return probabilities + [str(run.seed), time]


def table_header(caption: str, label: str, overview: bool) -> List[str]:
    return [
        r"\begin{table}[h!]",
        r"\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\small",
        r"\begin{tabular}{" + ("|c" * (10 if overview else 9)) + "|}",
        r"\hline",
        (r"R & " if overview else "") +
        r"$r_0$ & $r_m$ & $r_1$ & $p$ & $q$ & $r$ & $P_{boom}$ & Seed & Time (s) \\",
        r"\hline",
    ]


def render_tables(
    data: Dict[str, List[Run]],
    title: str = "CHACHA SINGLE KEY",
    label_prefix: str = "single-key-chacha",
    generator: str = "generate_single_key_chacha_latex_tables.py",
) -> str:
    names = sorted(data, key=test_directory_sort_key)
    output = [
        f"% {title} Test LaTeX Tables",
        f"% Auto-generated by {generator}",
        "% in course: no completion time in the log; -: no available solution",
        "",
        "% Table 1: Best Probability Results",
    ]
    output.extend(table_header(f"{title} Test Results - Best Probability",
                               f"tab:{label_prefix}-best-probability", True))
    for name in names:
        params = extract_test_params_from_dirname(name)
        cells = [str(value) for value in params] + result_cells(best_run(data[name]))
        output.append(" & ".join(cells) + r" \\")
    output.extend([r"\hline", r"\end{tabular}", r"\end{table}", "", ""])

    for name in names:
        rounds, r0, rm, r1 = extract_test_params_from_dirname(name)
        caption = (f"{title} {rounds} rounds "
                   f"($r_0$={r0}, $r_m$={rm}, $r_1$={r1}) - All Seeds")
        output.extend(table_header(caption, f"tab:{label_prefix}-{name}", False))
        best = best_run(data[name])
        for run in sorted(data[name], key=lambda item: item.seed):
            cells = [str(r0), str(rm), str(r1)] + result_cells(run)
            if run is best:
                cells = [bold_latex_cell(cell) for cell in cells]
            output.append(" & ".join(cells) + r" \\")
        output.extend([r"\hline", r"\end{tabular}", r"\end{table}", "", ""])
    return "\n".join(output)


def main() -> None:
    root = Path(__file__).resolve().parent
    data = collect_runs(root / "test_operation_modadd" / "test_single_key_chacha")
    output = root / "single_key_chacha_tables.tex"
    output.write_text(render_tables(data), encoding="utf-8")
    print(f"Generated {len(data) + 1} tables from "
          f"{sum(len(runs) for runs in data.values())} logs: {output}")


if __name__ == "__main__":
    main()
