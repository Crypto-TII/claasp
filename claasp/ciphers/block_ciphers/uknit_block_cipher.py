class UKNITBlockCipher(Cipher):
    """
    Construct an instance of the UKNITBlockCipher class.

    This class implements uKNIT Block Cipher, as defined in [HKPT2026]_.

    INPUT:

    - ``number_of_rounds`` -- **integer** (default: `12`); number of rounds of the cipher.

    EXAMPLES::

        sage: from claasp.ciphers.block_ciphers.uknit_block_cipher import UKNITBlockCipher
        sage: uknit = UKNITBlockCipher(number_of_rounds=12)
        sage: key = 0x0123456789abcdef0123456789abcdef
        sage: plaintext = 0x0123456789abcdef
        sage: ciphertext = 0x7d4ef882c1f42dba
        sage: uknit.evaluate([plaintext, key]) == ciphertext
        True
    """
    def __init__(self, number_of_rounds=12):
        self.block_bit_size = 64
        self.key_bit_size = 128

        super().__init__(
            family_name="uknit_block_cipher",
            cipher_type=BLOCK_CIPHER,
            cipher_inputs=[INPUT_PLAINTEXT, INPUT_KEY],
            cipher_inputs_bit_size=[self.block_bit_size, self.key_bit_size],
            cipher_output_bit_size=self.block_bit_size,
        )

        self.nrounds = min(len(ROUND_D_CYCLES), number_of_rounds)

        self.add_round()

        key_schedule_matrix = transpose_matrix(matrix_from_bit_function(apply_key_schedule_matrix))
        lfsr_matrix = transpose_matrix(matrix_from_bit_function(apply_lfsr))
        key_schedule_permutation = inverse_permutation(KEY_SCHEDULE_PERMUTATION)

        round_keys = [
            (INPUT_KEY, list(range(64))),
            (INPUT_KEY, list(range(64, 128))),
        ]

        k0_ref = round_keys[0]
        k1_ref = round_keys[1]

        for _ in range(2, self.nrounds + 1):
            k0_matrix_applied = self.add_linear_layer_component([k0_ref[0]], [k0_ref[1]], 64, key_schedule_matrix)
            k0_permuted = self.add_permutation_component(
                [k0_matrix_applied.id], [list(range(64))], 64, key_schedule_permutation, 4
            )
            k0_ref = (k0_permuted.id, list(range(64)))

            k1_lfsr_applied = self.add_linear_layer_component([k1_ref[0]], [k1_ref[1]], 64, lfsr_matrix)
            k1_matrix_applied = self.add_linear_layer_component([k1_lfsr_applied.id], [list(range(64))], 64, key_schedule_matrix)
            k1_permuted = self.add_permutation_component(
                [k1_matrix_applied.id], [list(range(64))], 64, key_schedule_permutation, 4
            )
            k1_ref = (k1_permuted.id, list(range(64)))

            round_key = self.add_xor_component([k0_ref[0], k1_ref[0]], [k0_ref[1], k1_ref[1]], 64)
            round_keys.append((round_key.id, list(range(64))))

        state = INPUT_PLAINTEXT

        for round_number in range(self.nrounds):
            self.add_round()

            round_key_id, round_key_positions = round_keys[round_number]

            xored = self.add_xor_component(
                [state, round_key_id],
                [list(range(64)), round_key_positions],
                64,
            )

            sbox_ids = []
            for position in range(16):
                lut = build_sbox_lut(ROUND_D_CYCLES[round_number][position], ROUND_B_CYCLES[round_number][position])
                sbox = self.add_sbox_component(
                    [xored.id],
                    [[4 * position + i for i in range(4)]],
                    4,
                    lut,
                )
                sbox_ids.append(sbox.id)

            if round_number < len(ROUND_LINEAR_SPARSE):
                matrix = transpose_matrix(build_linear_layer_matrix(ROUND_LINEAR_SPARSE[round_number]))
                linear = self.add_linear_layer_component(
                    sbox_ids,
                    [[0, 1, 2, 3]] * 16,
                    64,
                    matrix,
                )
                state = linear.id
            else:
                merged = self.add_permutation_component(
                    sbox_ids,
                    [[0, 1, 2, 3]] * 16,
                    64,
                    list(range(16)),
                    4,
                )
                state = merged.id

        final_key_id, final_key_positions = round_keys[self.nrounds]
        output = self.add_xor_component(
            [state, final_key_id],
            [list(range(64)), final_key_positions],
            64,
        )

        self.add_cipher_output_component([output.id], [list(range(64))], 64)
