MANTIS_SBOX = [0xc, 0xa, 0xd, 0x3, 0xe, 0xb, 0xf, 0x7, 0x8, 0x9, 0x1, 0x5, 0x0, 0x2, 0x4, 0x6]

KEY_SCHEDULE_PERMUTATION = [3, 8, 13, 2, 15, 9, 11, 5, 0, 6, 14, 10, 7, 12, 4, 1]

def apply_bit_permutation(nibble, permutation):
    bits = [(nibble >> (3 - i)) & 1 for i in range(4)]
    permuted_bits = [bits[permutation[i]] for i in range(4)]
    return (permuted_bits[0] << 3) | (permuted_bits[1] << 2) | (permuted_bits[2] << 1) | permuted_bits[3]

def build_sbox_lut(d_permutation, b_permutation):
    lut = []
    for x in range(16):
        y = apply_bit_permutation(x, b_permutation)
        y = MANTIS_SBOX[y]
        y = apply_bit_permutation(y, d_permutation)
        lut.append(y)
    return lut

def build_linear_layer_matrix(sparse_rows):
    return [[1 if column in row else 0 for column in range(64)] for row in sparse_rows]

def transpose_matrix(matrix):
    return [list(row) for row in zip(*matrix)]

def matrix_from_bit_function(function):
    matrix = [[0] * 64 for _ in range(64)]
    for column in range(64):
        output = function(1 << (63 - column))
        for row in range(64):
            if (output >> (63 - row)) & 1:
                matrix[row][column] = 1
    return matrix

def inverse_permutation(permutation):
    inverse = [0] * len(permutation)
    for index, value in enumerate(permutation):
        inverse[value] = index
    return inverse

def apply_nibble_permutation(value, permutation):
    nibbles = [(value >> (60 - 4 * i)) & 0xf for i in range(16)]
    permuted = [nibbles[permutation[i]] for i in range(16)]
    result = 0
    for n in permuted:
        result = (result << 4) | n
    return result

def apply_key_schedule_matrix(value):
    nibbles = [(value >> (60 - 4 * i)) & 0xf for i in range(16)]
    for block in range(4):
        base = block * 4
        nibbles[base + 3] ^= nibbles[base]
    result = 0
    for n in nibbles:
        result = (result << 4) | n
    return result

def apply_lfsr(value):
    nibbles = [(value >> (60 - 4 * i)) & 0xf for i in range(16)]
    updated = []
    for n in nibbles:
        x3 = (n >> 3) & 1
        x2 = (n >> 2) & 1
        x1 = (n >> 1) & 1
        x0 = n & 1
        updated.append((x2 << 3) | (x1 << 2) | (x0 << 1) | (x3 ^ x2))
    result = 0
    for n in updated:
        result = (result << 4) | n
    return result

def next_round_keys(k0, k1):
    new_k0 = apply_nibble_permutation(apply_key_schedule_matrix(k0), KEY_SCHEDULE_PERMUTATION)
    new_k1 = apply_nibble_permutation(apply_key_schedule_matrix(apply_lfsr(k1)), KEY_SCHEDULE_PERMUTATION)
    return new_k0, new_k1

