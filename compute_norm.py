def split_matrici(lista, size=4):
    blocco = size * size
    matrici = []

    for i in range(0, len(lista), blocco):
        chunk = lista[i:i+blocco]
        matrice = [chunk[j:j+size] for j in range(0, blocco, size)]
        matrici.append(matrice)

    return matrici

