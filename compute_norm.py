def operator_norm_p(A, p, samples=1000000):
    n = A.shape[1]
    best = 0

    for _ in range(samples):
        v = np.random.randn(n)
        v = v / np.linalg.norm(v, ord=p)

        val = np.linalg.norm(A @ v, ord=p)

        best = max(best, val)

    return best

