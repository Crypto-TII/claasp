def _assert_scalar_and_batch(primitive, values, expected):
    assert primitive.evaluate(*values) == expected
    decoded = {
        name: (primitive._decode_boundary(value, port.value_type),)
        for (name, port), value in zip(primitive.input_ports.items(), values)
    }
    result = BatchEvaluator().evaluate(primitive, decoded).outputs[0]
    assert primitive._encode_boundary(result, primitive.output.value_type) == expected


def test_aradi_hight_tea_xtea_and_raiden_vectors():
    _assert_scalar_and_batch(
        Aradi(),
        (0, 0x1F1E1D1C1B1A191817161514131211100F0E0D0C0B0A09080706050403020100),
        0x3F09ABF400E3BD7403260DEFB7C53912,
    )
    plaintext = 0x0011223344556677
    key = 0x000000066770000000A0000000000001
    _assert_scalar_and_batch(HIGHT(64, 128, 3, True, False), (plaintext, 0), 0x1055DDEE99BA66E0)
    _assert_scalar_and_batch(HIGHT(64, 128, 10, False, False), (plaintext, key), 0x2B8B6B285D2D0E9C)
    _assert_scalar_and_batch(HIGHT(), (plaintext, key), 0x3B25D694326C4375)
    vectors = (
        (TEA(), 0xBD7D764DFF0ADA1E, 0x1DE1C3C2C65880074C32DCE537B22AB3, 0x5E89B6140012C6DA),
        (TEA(32, 64, 32), 0xB779EE0A, 0x0E2DDD5C5B4CA9D4, 0x25476362),
        (XTEA(), 0xBD7D764DFF0ADA1E, 0x1DE1C3C2C65880074C32DCE537B22AB3, 0x91C0FEC24D17FE49),
        (XTEA(32, 64, 32), 0xB779EE0A, 0x0E2DDD5C5B4CA9D4, 0x5BE9022A),
        (Raiden(), 0xBD7D764DFF0ADA1E, 0x1DE1C3C2C65880074C32DCE537B22AB3, 0x99BF13C039B49812),
        (Raiden(32, 64, 32), 0xB779EE0A, 0x0E2DDD5C5B4CA9D4, 0x5A1674DF),
    )
    for primitive, value, secret, expected in vectors:
        _assert_scalar_and_batch(primitive, (value, secret), expected)


