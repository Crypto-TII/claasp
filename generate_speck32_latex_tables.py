#!/usr/bin/env python3
"""Generate Speck32 LaTeX tables from test_operation_modadd/test_speck32."""

from pathlib import Path

from generate_lea_latex_tables import (
    collect_all_test_data,
    create_latex_table_all_seeds,
    create_latex_table_best_probability,
    test_directory_sort_key,
)


def main(cipher: str = "speck32") -> None:
    root = Path(__file__).resolve().parent
    base_path = root / "test_operation_modadd" / f"test_{cipher}"
    if not base_path.is_dir():
        raise FileNotFoundError(f"{cipher.upper()} test directory not found: {base_path}")

    data_by_test = collect_all_test_data(str(base_path), cipher=cipher)
    if not data_by_test:
        raise ValueError(f"No complete {cipher.upper()} test results found in {base_path}")

    output = [
        f"% {cipher.upper()} Test LaTeX Tables",
        f"% Auto-generated by generate_{cipher}_latex_tables.py",
        "",
        "% Table 1: Best Probability Results",
        create_latex_table_best_probability(data_by_test, cipher=cipher),
        "",
        "",
        "% Tables 2+: All Seeds by Configuration",
    ]
    for test_name in sorted(data_by_test, key=test_directory_sort_key):
        results = data_by_test[test_name]
        output.extend([
            create_latex_table_all_seeds(test_name, results, cipher=cipher),
            "",
            "",
        ])

    output_file = root / f"{cipher}_tables.tex"
    output_file.write_text("\n".join(output), encoding="utf-8")
    count = sum(len(results) for results in data_by_test.values())
    print(f"Generated {len(data_by_test) + 1} tables from {count} logs: {output_file}")


if __name__ == "__main__":
    main()
